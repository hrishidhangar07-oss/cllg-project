    """Retrieve Gujarati translation data for a disease class."""
    if disease_key in GUJARATI_DISEASE_INFO:
        return GUJARATI_DISEASE_INFO[disease_key]
    
    parts = disease_key.split("___")
    crop_en = parts[0] if parts else "Plant"
    cond_en = parts[1].replace("_", " ") if len(parts) > 1 else "Unknown"
    is_healthy = "healthy" in cond_en.lower()
    
    crop_gu = CROP_GUJARATI.get(crop_en, crop_en)
